# SINCE THERE IS NO TOP BAR TO MOVE A FRAMELESS WINDOW OVER THE SCREEN WE HAVE TO DEFINE THE MOUSE EVENT THAT IS RESPONSIBLE FOR THE
# MOVEMENT. THIS FUNCTION MOVES window WHEN THE LEFT MOUSE BUTTON IS PRESSED AND DRAGGED OVER handle, THE FRAME ACTING AS ITS TOPBAR.
# THE WINDOW'S mousePressEvent HAS TO RECORD WHERE THE DRAG STARTED IN window.dragPos.
# beforeMove, IF GIVEN, IS CALLED FIRST: THE MAIN WINDOW USES IT TO LEAVE THE MAXIMISED STATE.
def dragBy(window, handle, beforeMove=None):
    window.dragPos = window.pos()  # INITIAL POSITION

    def moveWindow(event):
        if beforeMove:
            beforeMove()
        if event.buttons() == Qt.MouseButton.LeftButton:
            window.move(window.pos() + event.globalPosition().toPoint() - window.dragPos)
            window.dragPos = event.globalPosition().toPoint()
            event.accept()

    handle.mouseMoveEvent = moveWindow


# ----> FONT FALLBACK
# THE .ui FILES ASK FOR SEGOE UI, WHICH SHIPS WITH WINDOWS. WHERE IT IS MISSING, THE FIRST OF THESE THAT IS INSTALLED STANDS IN
# FOR ALL THREE OF ITS FAMILIES, AND THE SYSTEM'S OWN FONT IF NONE IS, SO A WINDOW DOES NOT END UP MIXING TWO TYPEFACES.
# A SUBSTITUTE HAS TO BE THE NAME OF AN INSTALLED FAMILY: A GENERIC NAME LIKE "Sans Serif" IS IGNORED.
# EACH WINDOW CALLS THIS BEFORE IT BUILDS ITS WIDGETS, BECAUSE A WIDGET KEEPS THE FONT IT RESOLVED WHEN IT WAS BUILT.
FONT_FALLBACKS = ["Noto Sans", "Helvetica Neue", "Arial"]


def setFontFallbacks():
    # QFontInfo GIVES THE FAMILY THE SYSTEM FONT RESOLVES TO; THE FONT ITSELF MAY ONLY SAY "Sans Serif".
    systemFamily = QtGui.QFontInfo(QtGui.QFontDatabase.systemFont(QtGui.QFontDatabase.SystemFont.GeneralFont)).family()
    for family in ("Segoe UI", "Segoe UI Light", "Segoe UI Semilight"):
        QtGui.QFont.insertSubstitutions(family, FONT_FALLBACKS + [systemFamily])


# ----> THE LOOK OF EVERY WIDGET IS IN ONE STYLESHEET, resources/style.qss, COMPILED INTO THE RESOURCES BY `just uic`.
# EACH OF THE THREE WINDOWS SETS IT ON ITS OWN CONTENT RATHER THAN ON THE WHOLE APPLICATION, SO THAT IT DOES NOT REACH
# QT'S OWN DIALOGS: A QMessageBox OR A QFileDialog OPENED FROM THE APP KEEPS ITS NORMAL LOOK.
def loadStyle():
    sheet = QtCore.QFile(":/style.qss")
    if not sheet.open(QtCore.QIODevice.OpenModeFlag.ReadOnly | QtCore.QIODevice.OpenModeFlag.Text):
        raise RuntimeError("style.qss is not in the compiled resources: run `just uic`")
    return bytes(sheet.readAll()).decode("utf-8")


# DIALOGBOX CLASS WHICH MAKE THE DIALOGBOX WHEN CALLED.
# ------> DIALOG BOX CLASS : DIALOGBOX CONTAINING TWO BUTTONS, ONE MAEEAGE BAR, ONE ICON HOLDER, ONE HEADING DEFINING
class dialogUi(QDialog):
    def __init__(self, parent=None):

        super(dialogUi, self).__init__(parent)
        setFontFallbacks()
        self.d = Ui_Dialog()
        self.d.setupUi(self)
        self.setStyleSheet(loadStyle())
        self.setWindowFlags(
            QtCore.Qt.FramelessWindowHint
        )  # REMOVING WINDOWS TOP BAR AND MAKING IT FRAMELESS (AS WE HAVE AMDE A CUSTOME FRAME IN THE WINDOW ITSELF)
        self.setAttribute(
            QtCore.Qt.WA_TranslucentBackground
        )  # MAKING THE WINDOW TRANSPARENT SO THAT TO GET A TRUE FLAT UI

        #############################################################################################                        -------(C1)
        # SINCE THERE IS NO WINDOWS TOPBAR, THE CLOSE MIN, MAX BUTTON ARE ABSENT AND SO THERE IS A NEED FOR THE ALTERNATIVE BUTTONS IN OUR
        # DIALOG BOX, WHICH IS CARRIED OUT BY THE BELOW CODE
        # -----> MINIMIZE BUTTON OF DIALOGBOX
        self.d.bn_min.clicked.connect(lambda: self.showMinimized())

        # -----> CLOSE APPLICATION FUNCTION BUTTON
        self.d.bn_close.clicked.connect(lambda: self.close())

        # -----> THE RIGHT HAND BUTTON ACCEPTS THE DIALOGBOX AND THE LEFT HAND ONE REJECTS IT, AS CLOSING IT DOES.
        # dialogexec() IN MainWindow RETURNS True WHEN IT WAS ACCEPTED.
        self.d.bn_east.clicked.connect(self.accept)
        self.d.bn_west.clicked.connect(self.reject)
        ##############################################################################################

        # ---> MOVING THE WINDOW WHEN LEFT MOUSE PRESSED AND DRAGGED OVER DIALOGBOX TOPBAR: SEE dragBy()
        dragBy(self, self.d.frame_top)

    # ----> FUNCTION TO CAPTURE THE INITIAL POSITION OF THE MOUSE
    def mousePressEvent(self, event):
        self.dragPos = event.globalPosition().toPoint()

    #################################################################################################

    #################################################################################################                        ------(C3)
    # THE DIALOG BOX IS DESIGNED TO BE CALLED FROM ANY WHERE IN THE UI WITH ABLE TO CHANGE THE STATRE OF THE TEXT SHOWN, BUTTON NAMES E.T.C
    # THIS IS MADE BY CALLING THIS FUNCTION WHICH TAKES: HEADING, MESSAGE, ICON, BUTTON NAME 1, BUTTON NAME 2 AS ARUMENT.
    # EMBED THE GIVEN PROPERT TO THE DIALOGBOX AND FINALLY DISPLAYS IT IN THE WINDOW.
    # -------> SETTING THE DIALOGBOX CONFIGRATION: TEXT IN BUTTON, LABEL, HEADING
    def dialogConstrict(self, heading, message, icon, btn1, btn2):
        self.d.lab_heading.setText(heading)
        self.d.lab_message.setText(message)
        self.d.bn_east.setText(btn2)
        self.d.bn_west.setText(btn1)
        pixmap = QtGui.QPixmap(icon)
        self.d.lab_icon.setPixmap(pixmap)

    ##################################################################################################


